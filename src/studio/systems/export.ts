import type { PublicProjection } from "./projection";

// Builds `utils/data/products-data.ts` from the public projection (spec 0008, AC-10). Pure string building: the
// types, `statusSections`, and comments are written literally, strings go through JSON.stringify, and long lines
// wrap the way the hand edited file did (120 columns), so a drop in replacement passes lint and build unchanged.

const WIDTH = 120;

const HEADER = `// Public product ecosystem data for the /products page (spec 0002).
// PUBLIC FIELDS ONLY: id, name, status, summary, the optional standalone flag, and the links between products.
// Never add notes, lessons, stack, repo links, ticket keys, or client references here.
// The private source of truth is the SMB Systems Map; summaries below are rewritten for the public.
// Generated by the studio export (spec 0008). Edit systems in the studio, then export again.
`;

const TYPES = `export type ProductStatus = "built" | "in-progress" | "next" | "planned";

export type PublicProduct = {
  id: ProductId;
  name: string;
  status: ProductStatus;
  summary: string;
  // Set only where the map's group is "standalone"; never false. Changes only the empty connections message.
  standalone?: true;
};

export type ProductLink = {
  from: ProductId;
  to: ProductId;
  label: string;
  state: "live" | "planned";
};

export const statusSections: { status: ProductStatus; title: string }[] = [
  { status: "built", title: "Built" },
  { status: "in-progress", title: "In progress" },
  { status: "next", title: "Up next" },
  { status: "planned", title: "Planned" },
];
`;

const q = (value: string) => JSON.stringify(value);

function productIdType(ids: string[]): string {
  const oneLine = `export type ProductId = ${ids.map(q).join(" | ")};`;
  if (oneLine.length <= WIDTH) {
    return `${oneLine}\n`;
  }
  return `export type ProductId =\n${ids.map((id, index) => `  | ${q(id)}${index === ids.length - 1 ? ";" : ""}`).join("\n")}\n`;
}

function summaryLines(summary: string): string {
  const oneLine = `    summary: ${q(summary)},`;
  return oneLine.length <= WIDTH ? `${oneLine}\n` : `    summary:\n      ${q(summary)},\n`;
}

function productEntry(system: PublicProjection["systems"][number]): string {
  return (
    "  {\n" +
    `    id: ${q(system.id)},\n` +
    `    name: ${q(system.name)},\n` +
    `    status: ${q(system.status)},\n` +
    (system.standalone ? "    standalone: true,\n" : "") +
    summaryLines(system.summary) +
    "  },\n"
  );
}

function linkEntry(link: PublicProjection["links"][number]): string {
  const fields = [`from: ${q(link.from)}`, `to: ${q(link.to)}`, `label: ${q(link.label)}`, `state: ${q(link.state)}`];
  const oneLine = `  { ${fields.join(", ")} },`;
  return oneLine.length <= WIDTH ? `${oneLine}\n` : `  {\n${fields.map((field) => `    ${field},\n`).join("")}  },\n`;
}

// The caller refuses an empty projection first (NothingToExport), so the public page is never emptied by accident.
export function buildPublicProductsFile(projection: PublicProjection): string {
  return (
    HEADER +
    "\n" +
    productIdType(projection.systems.map((system) => system.id)) +
    "\n" +
    TYPES +
    "\n" +
    "// Display order within each status section follows this array.\n" +
    "export const products: PublicProduct[] = [\n" +
    projection.systems.map(productEntry).join("") +
    "];\n" +
    "\n" +
    "export const productLinks: ProductLink[] = [\n" +
    projection.links.map(linkEntry).join("") +
    "];\n"
  );
}
